#!/usr/bin/env python3
"""Which Hebrew vowel, cantillation and punctuation marks each font lacks.

Reads the font files themselves, from a checkout of github.com/google/fonts,
and writes the table the add-on uses to borrow the marks a font is missing
(see apps-script/server/hebrew-fonts.gs):

  apps-script/server/hebrew-font-coverage.gs   (server: the insert)
  apps-script/shared/fonts/coverage.html        (client: the preview)

Both are generated from the same data, and test/tests/hebrew-fonts.test.js
checks that they agree. Never edit them by hand; re-run this instead.

Usage (see README.md in this folder):

  python3 generate.py /path/to/google-fonts-checkout

Needs fontTools (pip install fonttools). A development tool only: nothing in
this folder is pushed to Apps Script.
"""

import json
import os
import re
import sys

from fontTools.ttLib import TTFont

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

# The marks the add-on may borrow: everything in the Hebrew block that is not
# a letter. Cantillation U+0591-05AF, vowels and points U+05B0-05C7 (which
# include maqaf, paseq and sof pasuq), and geresh / gershayim. Letters
# (U+05D0-05EA) and the Yiddish ligatures are never borrowed.
MARKS = list(range(0x0591, 0x05C8)) + [0x05F3, 0x05F4]
LETTERS = list(range(0x05D0, 0x05EB))

# Google Fonts categories -> which Noto Hebrew the missing marks come from.
SERIF_CATEGORIES = {'SERIF'}


def ranges(codepoints):
    """[0x591, 0x592, 0x5c6] -> '0591-0592,05C6'"""
    out = []
    for cp in sorted(codepoints):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return ','.join('%04X' % a if a == b else '%04X-%04X' % (a, b) for a, b in out)


def metadata_field(text, name):
    match = re.search(r'^%s:\s*"([^"]*)"' % name, text, re.M)
    return match.group(1) if match else ''


def read_family(directory):
    with open(os.path.join(directory, 'METADATA.pb'), encoding='utf-8') as handle:
        meta = handle.read()
    if 'subsets: "hebrew"' not in meta:
        return None
    files = re.findall(r'filename:\s*"([^"]+)"', meta)
    # The regular (or the variable font), else the first listed.
    files.sort(key=lambda name: (0 if re.search(r'(-Regular|\[)', name) else 1))
    font = TTFont(os.path.join(directory, files[0]), lazy=True)
    cmap = font.getBestCmap()
    if not all(letter in cmap for letter in LETTERS):
        return None
    return {
        'name': metadata_field(meta, 'name'),
        'style': 'serif' if metadata_field(meta, 'category') in SERIF_CATEGORIES else 'sans',
        'missing': ranges(cp for cp in MARKS if cp not in cmap),
    }


def main(checkout):
    families = {}
    for licence in ('ofl', 'apache', 'ufl'):
        root = os.path.join(checkout, licence)
        if not os.path.isdir(root):
            continue
        for entry in sorted(os.listdir(root)):
            directory = os.path.join(root, entry)
            if not os.path.isfile(os.path.join(directory, 'METADATA.pb')):
                continue
            family = read_family(directory)
            if family:
                families[family['name']] = {'style': family['style'], 'missing': family['missing']}
    if not families:
        sys.exit('No Hebrew families found under %s' % checkout)
    for fallback in ('Noto Serif Hebrew', 'Noto Sans Hebrew'):
        if families.get(fallback, {}).get('missing', 'x') != '':
            sys.exit('%s no longer has every mark; pick another fallback.' % fallback)

    data = dict(sorted(families.items()))
    body = json.dumps(data, indent=2, ensure_ascii=True)
    header = ('Generated by tools/hebrew-font-coverage/generate.py from the font files in '
              'google/fonts. Do not edit; re-run the generator. For each Google Font with '
              'Hebrew letters: "serif" or "sans" (which Noto Hebrew lends it marks) and the '
              'Hebrew marks it has no glyph for, as code point ranges.')

    with open(os.path.join(REPO, 'apps-script/server/hebrew-font-coverage.gs'), 'w', encoding='utf-8') as out:
        out.write('// %s\n// See apps-script/server/hebrew-fonts.gs.\n' % header)
        out.write('var HEBREW_FONT_COVERAGE_ = %s;\n' % body)

    os.makedirs(os.path.join(REPO, 'apps-script/shared/fonts'), exist_ok=True)
    with open(os.path.join(REPO, 'apps-script/shared/fonts/coverage.html'), 'w', encoding='utf-8') as out:
        out.write('<script>\n// %s\n// See shared/fonts/js.html.\n' % header)
        out.write('var HEBREW_FONT_COVERAGE = %s;\n</script>\n' % body)

    print('%d Hebrew families; %d missing some marks.' % (
        len(data), sum(1 for f in data.values() if f['missing'])))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
