// Reading conventions of the transliteration (apps-script/transliteration.gs):
//
//   1. The Name is read "HaShem", not spelled out (yehvah, yy, h'): יהוה and
//      every substitute for it (יי, יקוק, ה', השם), prefixes kept (laHaShem).
//   2. Each sentence starts with a capital, as English is written: the start
//      of a line, and after a sof pasuq or a period. IPA is left alone.
//   3. Names of people, places and peoples are capitalized: the Tanakh's
//      (by their pointing, else their consonants) and the Talmud's sages and
//      places, a sage's title with them.
//
// Also: every cantillation mark (and meteg) is dropped from the Latin text;
// only the first one was, and the rest were copied into it.
//
// Loaded with vm.runInContext; see AGENTS.md hard rule #3.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const context = {
  console,
  PropertiesService: { getUserProperties: () => ({ getProperty: () => null }) },
};
vm.createContext(context);
for (const file of ['apps-script/server/utils.gs', 'apps-script/gematriya.gs', 'apps-script/transliteration.gs']) {
  vm.runInContext(fs.readFileSync(file, 'utf8'), context, { filename: file });
}
const tr = (text, scheme = 'simple_english') => context.transliterateHebrewText(text, scheme, { overrideMap: {} });

// Deuteronomy 6:4-5, as Sefaria sends it.
const SHEMA = 'שְׁמַ֖ע יִשְׂרָאֵ֑ל יְהוָ֥ה אֱלֹהֵ֖ינוּ יְהוָ֥ה ׀ אֶחָֽד׃ וְאָ֣הַבְתָּ֔ אֵ֖ת יְהוָ֣ה אֱלֹהֶ֑יךָ';
// Hebrew vowel and cantillation marks; paseq and sof pasuq are punctuation.
const HEBREW_MARK = /[\u0591-\u05BD\u05BF\u05C1\u05C2\u05C4\u05C5\u05C7]/;

test('the Name is read HaShem, with or without vowels and cantillation', () => {
  for (const name of ['יְהוָ֥ה', 'יְהֹוָה', 'יהוה']) assert.equal(tr(`כִּי ${name}`), `${tr('כִּי')} HaShem`, name);
  assert.match(tr(SHEMA), /^Shema yisera'el HaShem 'eloheynv HaShem ׀ 'ekhad׃ Ve'ahaveta 'et HaShem /);
});

test('every substitute for the Name is read HaShem too', () => {
  for (const name of ['יי', 'יְיָ֥', 'יקוק', 'יְקוָק', "ה'", 'ה׳', 'השם', 'הַשֵּׁם']) {
    assert.equal(tr(`בָּרוּךְ ${name}`), `${tr('בָּרוּךְ')} HaShem`, name);
  }
});

test('a prefix keeps its own reading', () => {
  assert.equal(tr('לַיהוָה'), 'LaHaShem');
  assert.equal(tr('שִׁירוּ לַיהוָה'), `${tr('שִׁירוּ')} laHaShem`);
  assert.equal(tr('וַיהוָה'), 'VaHaShem');
  assert.equal(tr('לַייָ'), 'LaHaShem');
  assert.match(tr('וּבַיהוָה'), /^[A-Z][a-z]*HaShem$/); // two prefix letters
});

test('words that only contain the letters are not the Name', () => {
  for (const word of ['יְהוּדָה', 'יהודה', 'הַשָּׁמַיִם', 'וַיְהִי', 'הָיָה']) {
    assert.doesNotMatch(tr(word), /HaShem/, word);
  }
});

test('IPA reads the Name in IPA, and is never capitalized', () => {
  assert.equal(tr('כִּי יְהוָה', 'ipa_modern'), `${tr('כִּי', 'ipa_modern')} haʃem`);
  assert.match(tr('כִּי', 'ipa_modern'), /^k/);
  assert.equal(tr('אֶחָד׃ וְאָהַבְתָּ', 'ipa_modern'), 'ʔeχad׃ veʔahaveta');
});

test('each sentence starts with a capital: the line, after a sof pasuq or a period', () => {
  assert.equal(tr('אֶחָד׃ וְאָהַבְתָּ'), "'Ekhad׃ Ve'ahaveta");
  // After a period, and not after an ordinary word.
  assert.match(tr('מֵאֵימָתַי קוֹרִין. מִשָּׁעָה'), /^Me'eymatay [a-z]\S*\. M/);
  // The line marker and the aleph sign are skipped.
  assert.match(tr('(א) בְּרֵאשִׁית בָּרָא'), /^\(\S*\) Bere'shiyt bara'$/);
  assert.equal(tr('אֶחָד'), "'Ekhad");
  // Every scheme with letters that have capitals.
  assert.match(tr('שְׁמַע יִשְׂרָאֵל', 'academic_full'), /^Šəmaʿ /);
  assert.match(tr('שְׁמַע יִשְׂרָאֵל', 'ashkenazi'), /^Shema /);
});

test('no Hebrew vowel or cantillation mark is left in the Latin text', () => {
  for (const scheme of ['simple_english', 'traditional', 'academic_full', 'ipa_modern']) {
    assert.doesNotMatch(tr(SHEMA, scheme), HEBREW_MARK, scheme);
  }
});

test('the insert path (line by line) capitalizes each line', () => {
  const out = context.transliterateHebrewHtmlPreservingBasicBreaks('אֶחָד<br>וְאָהַבְתָּ <b>אֵת</b> יְהוָה', 'simple_english', { overrideMap: {} });
  assert.equal(out, "'Ekhad\nVe'ahaveta 'et HaShem");
});

// ── Names of people, places and peoples ──────────────────────────────────
//
// Capitalized from server/proper-names.gs (generated by
// tools/proper-names/generate.py from STEPBible's tagged Tanakh and
// tools/proper-names/talmud-names.txt).

const withNames = { console, PropertiesService: context.PropertiesService };
vm.createContext(withNames);
for (const file of ['apps-script/server/utils.gs', 'apps-script/gematriya.gs', 'apps-script/server/proper-names.gs', 'apps-script/transliteration.gs']) {
  vm.runInContext(fs.readFileSync(file, 'utf8'), withNames, { filename: file });
}
const named = (text, scheme = 'simple_english') => withNames.transliterateHebrewText(text, scheme, { overrideMap: {} });
// The Latin words with a capital in them (meKharan), but the first: it starts
// the sentence.
const capitals = (text) => named(text).split(' ').slice(1).filter((w) => /[A-Z]/.test(w));

test('people and places in the Tanakh are capitalized, after their prefix', () => {
  assert.deepEqual(capitals('וַיֵּלֶךְ אַבְרָם וַיֵּלֶךְ אִתּוֹ לוֹט מֵחָרָן'), ["'Averam", 'Lvot', 'meKharan']);
  assert.deepEqual(capitals('וַיֵּצֵא מֹשֶׁה מִמִּצְרַיִם אֶל בָּבֶל'), ['Mosheh', 'miMitserayim', 'Bavel']);
  assert.deepEqual(capitals('עָשׂוּ כֵן בְּנֵי יִשְׂרָאֵל'), ["Yisera'el"]);
});

test('the pointing tells a name from a word spelled alike', () => {
  // עֵשָׂו is Esau; עָשׂוּ is "they did". שָׁאוּל is Saul; שְׁאוֹל is Sheol.
  assert.deepEqual(capitals('וַיָּבֹא עֵשָׂו וַיַּעַשׂ כֵּן עָשׂוּ'), ["'Esav"]);
  assert.deepEqual(capitals('וַיֵּרֶד שָׁאוּל שְׁאוֹל'), ["Sha'vl"]);
  // A common word is never capitalized: אשר is Asher 29 times, "which" 4,807.
  assert.deepEqual(capitals('וַיֹּאמֶר אֲשֶׁר אָמַר'), []);
});

test('unpointed text is read by its consonants', () => {
  assert.deepEqual(capitals('ויצא משה מירושלים'), ['Mshh', 'mYrvshlym']);
});

test('a two-word name whose first word is also a word: Beit El, Be\'er Sheva', () => {
  assert.deepEqual(capitals('וַיִּקְרָא שֵׁם הַמָּקוֹם בֵּית־אֵל'), ["Beyt־'El"]);
  assert.match(named('וַיֵּלֶךְ בְּאֵר שָׁבַע'), / Be'er Shava'$/);
  // בֵּית alone is "house".
  assert.deepEqual(capitals('אֶל בֵּית אָבִיו'), []);
});

test('Talmud sages and places, with their titles and prefixes', () => {
  assert.deepEqual(capitals('דִּבְרֵי רַבִּי אֱלִיעֶזֶר. רַבָּן גַּמְלִיאֵל אוֹמֵר'), ["Rabiy", "'Eliy'ezer.", 'Raban', "Gameliy'el"]);
  // Prefixes: ו, ד (of), ב (in).
  assert.deepEqual(capitals("אמר רבא משמיה דשמואל ואביי בפומבדיתא"), ['Rv', "dShmv'l", "v'Vyy", "vFvmvdyt'"]);
  // A title before a name is capitalized, and ר' abbreviates Rabbi.
  assert.deepEqual(capitals("אמר רב נחמן ור' יהושע בן לוי"), ['Rv', 'Nkhmn', 'vR', 'Yhvsh', 'Lvy']);
});

test('a Talmud name that is also a word is capitalized only after a title or ben', () => {
  // מאיר "gives light", ששת "six"; הרבה "much" is not Rabbah.
  assert.deepEqual(capitals('אמר רבי מאיר אומר מאיר'), ['Rvy', "M'yr"]);
  assert.deepEqual(capitals('אמר רב ששת ששת ימים'), ['Rv', 'Shsht']);
  assert.deepEqual(capitals('הרבה מרבה'), []);
});

test('IPA capitalizes no name', () => {
  assert.doesNotMatch(named('וַיֵּצֵא מֹשֶׁה מִמִּצְרַיִם', 'ipa_modern'), /[A-Z]/);
});

test('the generated pointed spellings are keyed exactly as pointedKey_ keys them', () => {
  // generate.py's pointed_key and transliteration.gs's pointedKey_ must agree,
  // or a pointed name is never found.
  const pointed = vm.runInContext('PROPER_NAMES_POINTED_', withNames).split(' ').map((w) => w.slice(0, -1));
  assert.ok(pointed.length > 4000, pointed.length);
  const drift = pointed.filter((key) => withNames.pointedKey_(key) !== key);
  assert.deepEqual(drift.slice(0, 5), []);
  // And a word as Sefaria sends it (cantillation, meteg) finds its entry.
  assert.ok(pointed.includes(withNames.pointedKey_('יְרוּשָׁלִַ֖ם'.replace(/[\u0591-\u05AF\u05BD]/g, ''))));
});

test('proper-names.gs is generated, and credits its source', () => {
  const source = fs.readFileSync('apps-script/server/proper-names.gs', 'utf8');
  assert.match(source, /^\/\/ Generated by tools\/proper-names\/generate\.py/);
  assert.match(source, /STEPBible.*CC BY 4\.0/s);
});
